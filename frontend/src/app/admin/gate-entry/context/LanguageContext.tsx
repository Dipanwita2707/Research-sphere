const VOWEL_INDEPENDENT: Record<string, string> = {
  aa: 'आ', ai: 'ऐ', au: 'औ', ee: 'ई', ii: 'ई', oo: 'ऊ', uu: 'ऊ',
  a: 'अ', e: 'ए', i: 'इ', o: 'ओ', u: 'उ'
};

const VOWEL_MATRA: Record<string, string> = {
  aa: 'ा', ai: 'ै', au: 'ौ', ee: 'ी', ii: 'ी', oo: 'ू', uu: 'ू',
  a: '', e: 'े', i: 'ि', o: 'ो', u: 'ु'
};

const CONSONANT_MAP: Record<string, string> = {
  chh: 'छ', kh: 'ख', gh: 'घ', jh: 'झ', th: 'थ', dh: 'ध', ph: 'फ', bh: 'भ', sh: 'श',
  ch: 'च', ng: 'ङ', ny: 'ञ',
  k: 'क', g: 'ग', j: 'ज', t: 'ट', d: 'ड', n: 'न', p: 'प', b: 'ब', m: 'म',
  y: 'य', r: 'र', l: 'ल', v: 'व', w: 'व', s: 'स', h: 'ह', f: 'फ', z: 'ज',
  q: 'क', x: 'क्स', c: 'क'
};

const CONSONANT_KEYS = Object.keys(CONSONANT_MAP).sort((a, b) => b.length - a.length);
const VOWEL_KEYS = Object.keys(VOWEL_MATRA).sort((a, b) => b.length - a.length);

function transliterateWordToHindi(word: string): string {
  const direct = TOKEN_MAP_HI[word.toLowerCase()];
  if (direct) return direct;
  if (!/^[A-Za-z]+$/.test(word)) return word;

  const lower = word.toLowerCase();
  let i = 0;
  let output = '';

  while (i < lower.length) {
    let matchedConsonant = '';
    for (const key of CONSONANT_KEYS) {
      if (lower.startsWith(key, i)) {
        matchedConsonant = key;
        break;
      }
    }

    if (matchedConsonant) {
      const consonantChar = CONSONANT_MAP[matchedConsonant];
      i += matchedConsonant.length;

      let matchedVowel = 'a';
      for (const vowel of VOWEL_KEYS) {
        if (lower.startsWith(vowel, i)) {
          matchedVowel = vowel;
          i += vowel.length;
          break;
        }
      }

      output += consonantChar + (VOWEL_MATRA[matchedVowel] ?? '');
      continue;
    }

    let matchedVowel = '';
    for (const vowel of VOWEL_KEYS) {
      if (lower.startsWith(vowel, i)) {
        matchedVowel = vowel;
        break;
      }
    }

    if (matchedVowel) {
      output += VOWEL_INDEPENDENT[matchedVowel] || matchedVowel;
      i += matchedVowel.length;
      continue;
    }

    output += word[i];
    i += 1;
  }

  return output || word;
}

function localizeDisplayText(text: string, language: Language): string {
  if (!text || language !== 'hi' || DEVANAGARI_RE.test(text)) return text;

  const normalized = text.trim().toLowerCase();
  if (PHRASE_MAP_HI[normalized]) return PHRASE_MAP_HI[normalized];

  return text
    .split(WORD_SPLIT_RE)
    .map((part) => {
      if (!part || WORD_SPLIT_RE.test(part)) return part;
      if (/\d/.test(part) || /^[A-Z0-9]+$/.test(part)) return part;
      const direct = TOKEN_MAP_HI[part.toLowerCase()];
      if (direct) return direct;
      return transliterateWordToHindi(part);
    })
    .join('');
}

